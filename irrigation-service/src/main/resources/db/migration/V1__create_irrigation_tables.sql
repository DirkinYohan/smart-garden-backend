CREATE TABLE crop_profile (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(64)              NOT NULL UNIQUE,
    min_moisture INTEGER                  NOT NULL,
    max_moisture INTEGER                  NOT NULL,
    description  VARCHAR(255),
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Single-row table: the garden has one irrigation configuration (id = 1).
CREATE TABLE irrigation_config (
    id               BIGINT PRIMARY KEY,
    mode             VARCHAR(16)              NOT NULL,
    crop_profile_id  BIGINT REFERENCES crop_profile (id),
    min_moisture     INTEGER                  NOT NULL,
    max_moisture     INTEGER                  NOT NULL,
    rain_pause       BOOLEAN                  NOT NULL,
    ai_enabled       BOOLEAN                  NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by       VARCHAR(16)              NOT NULL,
    last_analysis_id VARCHAR(64)
);
