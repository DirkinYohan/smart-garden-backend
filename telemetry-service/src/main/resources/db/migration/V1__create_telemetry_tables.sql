CREATE TABLE telemetry_reading (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id    VARCHAR(64)              NOT NULL,
    raw          INTEGER                  NOT NULL,
    moisture     INTEGER                  NOT NULL,
    pump_on      BOOLEAN                  NOT NULL,
    sensor_ok    BOOLEAN                  NOT NULL,
    mode         VARCHAR(16)              NOT NULL,
    min_moisture INTEGER                  NOT NULL,
    max_moisture INTEGER                  NOT NULL,
    rain_pause   BOOLEAN                  NOT NULL,
    uptime_ms    BIGINT                   NOT NULL,
    received_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_telemetry_reading_received_at ON telemetry_reading (received_at);

CREATE TABLE irrigation_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id      VARCHAR(64)              NOT NULL,
    started_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at       TIMESTAMP WITH TIME ZONE,
    duration_sec   BIGINT,
    start_moisture INTEGER                  NOT NULL,
    end_moisture   INTEGER,
    mode           VARCHAR(16)              NOT NULL
);

CREATE INDEX idx_irrigation_event_started_at ON irrigation_event (started_at);
